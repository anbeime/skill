/**
 * [INPUT]: 项目目录与 BeatAPI 共享语言配置
 * [OUTPUT]: 项目事实、Paraglide 消息与静态消息适配器
 * [POS]: 上游目录到 BeatAPI 的生成边界，保留原文及证据
 * [PROTOCOL]: 变更时更新此头部，然后检查 AGENTS.md
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const output = process.argv[2];
if (!output) throw new Error('Usage: node scripts/export-website-data.mjs <output-file>');

const catalogue = JSON.parse(
  await readFile(new URL('../data/projects.json', import.meta.url), 'utf8'),
);
const catalogueHash = createHash('sha256').update(JSON.stringify(catalogue)).digest('hex');
const root = resolve(dirname(output), '../..');
const locales = JSON.parse(execFileSync('pnpm', ['exec', 'tsx', '-e',
  "import { locales } from './src/config/locale/index.ts'; console.log(JSON.stringify(locales))",
], { cwd: root, encoding: 'utf8' }));
const scope = resolve(root, 'messages/marketing/jev-projects');
await mkdir(scope, { recursive: true });
const key = (id, field) => `jev_projects.${id}.${field}`;
const projects = catalogue.projects.map(({ summary, decision, ...facts }) => ({
  ...facts, summaryKey: key(facts.id, 'summary'), decisionKey: key(facts.id, 'decision'),
}));
for (const locale of locales) {
  const messages = {};
  for (const project of catalogue.projects) {
    for (const field of ['summary', 'decision']) {
      if (typeof project[field][locale] !== 'string') throw new Error(`Missing ${locale}: ${project.id}.${field}`);
      messages[key(project.id, field)] = project[field][locale];
    }
  }
  await writeFile(resolve(scope, `${locale}.json`), `${JSON.stringify(messages, null, 2)}\n`);
}
await writeFile(resolve(root, 'src/blocks/jev-project-copy.ts'), `/**
 * [INPUT]: Paraglide 项目消息与共享语言身份
 * [OUTPUT]: 有限静态消息映射，按显式语言求值
 * [POS]: 自动生成的画廊文案适配器；不在事实目录中引入消息运行时
 * [PROTOCOL]: 变更时更新此头部，然后检查 AGENTS.md
 */
// Generated by BeatAPI/awesome-jev. Do not edit.
import type { SiteLocale } from '@/config/locale';
import { m } from '@/paraglide/messages.js';

const messages = {
${catalogue.projects.flatMap(project => ['summary', 'decision'].map(field => `  '${key(project.id, field)}': m['${key(project.id, field)}'],`)).join('\n')}
};

export function getJevProjectText(key: keyof typeof messages, locale: SiteLocale) {
  return messages[key]({}, { locale });
}
`);

const source = `/**
 * [INPUT]: BeatAPI/awesome-jev 的项目目录
 * [OUTPUT]: 项目事实与文案键，不携带本地化正文
 * [POS]: 自动生成的画廊事实源；文案由 blocks/jev-project-copy 求值
 * [PROTOCOL]: 变更时更新此头部，然后检查 AGENTS.md
 */
// Generated from BeatAPI/awesome-jev data/projects.json. Do not edit project rows by hand.

export type JevProjectCategory =
  | 'agent-workflows'
  | 'developer-tools'
  | 'search-data'
  | 'open-models'
  | 'interfaces'
  | 'safety-review'
  | 'browser-computer-use'
  | 'sdk-integrations'
  | 'routing-optimization'
  | 'domain-tools';

export type JevProjectId = ${catalogue.projects.map(project => JSON.stringify(project.id)).join(' | ')};

export type JevProject = {
  id: string;
  name: string;
  owner: string;
  repoUrl: string;
  evidenceUrl: string;
  modelUrl?: string;
  source: { type: 'x' | 'github' | 'huggingface'; label: string; url: string; author?: string; views?: number };
  category: JevProjectCategory;
  language: string;
  license: string;
  starsAtCapture: number;
  summaryKey: \`jev_projects.\${JevProjectId}.summary\`;
  decisionKey: \`jev_projects.\${JevProjectId}.decision\`;
  verification: 'source-reviewed';
  runtimeVerified: false;
};

export const JEV_PROJECTS_CAPTURED_AT = '${catalogue.capturedAt}';
export const JEV_PROJECTS_REPOSITORY = 'https://github.com/BeatAPI/awesome-jev';
export const JEV_PROJECTS_SOURCE_SHA256 = '${catalogueHash}';
export const JEV_PROJECTS_STAR_FLOOR = 50;

export const jevProjects = ${JSON.stringify(projects, null, 2)} as const satisfies readonly JevProject[];
`;

await writeFile(resolve(output), source);
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', resolve(output), resolve(root, 'src/blocks/jev-project-copy.ts')], { cwd: root });
console.log(`Exported ${catalogue.projects.length} projects to ${resolve(output)}`);
